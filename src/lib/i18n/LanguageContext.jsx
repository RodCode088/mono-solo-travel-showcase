const dictionaries = { en };

function normalizeLanguage(value) {
  return languages.some((language) => language.code === value) ? value : FALLBACK_LANGUAGE;
}

function getInitialLanguage() {
  if (typeof window === "undefined") return DEFAULT_LANGUAGE;
  const stored = window.localStorage.getItem(STORAGE_KEY);
  if (stored) return normalizeLanguage(stored);
  // El catalogo publico abre en ingles. No leer el locale del navegador: la
  // eleccion guardada de un visitante que vuelve gana, todos los demas
  // reciben EN y pueden cambiar a ES desde el header.
  return DEFAULT_LANGUAGE;
}

function translate(text, language) {
  if (language === FALLBACK_LANGUAGE || text == null) return text;
  return dictionaries[language]?.[text] || text;
}

function translateArray(items, language) {
  return Array.isArray(items) ? items.map((item) => translate(item, language)) : items;
}

function localizedExperience(experience, language) {
  const localized = experience?.translations?.[language] || experience?.translations?.es || {};
  return {
    title: localized.title || experience?.title,
    shortDescription: localized.shortDescription || experience?.shortDescription,
    fullDescription: localized.fullDescription || experience?.fullDescription,
    itinerary: localized.itinerary?.length ? localized.itinerary : experience?.itinerary,
    destination: translate(experience?.destination, language),
    category: translate(experience?.category, language),
    meetingPoint: translate(experience?.meetingPoint, language),
    included: translateArray(experience?.included, language),
    notIncluded: translateArray(experience?.notIncluded, language),
    requirements: translateArray(experience?.requirements, language),
    cancellationPolicy: translate(experience?.cancellationPolicy, language),
  };
}

const LanguageContext = createContext(null);

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getInitialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    window.localStorage.setItem(STORAGE_KEY, language);
  }, [language]);

  const value = useMemo(() => ({
    language,
    languages,
    setLanguage: (next) => setLanguageState(normalizeLanguage(next)),
    t: (text) => translate(text, language),
    list: (items) => translateArray(items, language),
    experience: (item) => localizedExperience(item, language),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}
